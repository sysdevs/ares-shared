    #[test]
    fn opcodes_are_unique_and_pointers_sorted() {
        let mut ids: Vec<i32> = OPCODES.iter().map(|o| o.1).collect();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), OPCODES.len());
        assert!(POINTERS.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(POINTERS.iter().all(|p| name(p.0).is_some()));
    }

    #[test]
    fn operand_sizes() {
        assert!(large_operand(op::PUSH_CONSTANT_INT) && large_operand(op::POP_ARRAY_INT) && large_operand(op::GET_VARC_INT));
        assert!(!large_operand(100));
        assert!(!large_operand(op::RETURN) && !large_operand(op::GOSUB) && !large_operand(op::ADD));
    }
